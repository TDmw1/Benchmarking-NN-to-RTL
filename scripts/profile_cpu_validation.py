"""
=============================================================================
CPU PIPELINE VALIDATION - Run on MAC
NOTE: The data generated by this script is for the pipeline methodology check
These latency numbers are measured on a Mac CPU and DO NOT represent the
final control data.

True control_baseline.csv numbers will be collected by running this exact 
script on the target edge board's CPU core.
=============================================================================
"""

import os
import time
import numpy as np
import pandas as pd
import onnxruntime as ort

MODELS = ["mlp_small", "cnn_lenet", "cnn_skip", "cnn_unusual_op"]
CSV_PATH = os.path.join(os.path.dirname(__file__), "..", "data_tables", "control_baseline.csv")
os.makedirs(os.path.dirname(CSV_PATH), exist_ok=True)

WARMUP_RUNS = 10
INFERENCE_RUNS = 100

results = []

def profile_model(model_path, model_name, precision):
    if not os.path.exists(model_path):
        print(f"[Profile - {model_name} ({precision})] Skipped: Not found at {model_path}")
        return

    # 1. Measure Session Init Time
    t0 = time.perf_counter()
    sess_options = ort.SessionOptions()
    sess_options.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
    sess = ort.InferenceSession(model_path, sess_options, providers=['CPUExecutionProvider'])
    init_time_ms = (time.perf_counter() - t0) * 1000.0

    # Dynamically grab input shape and type from the graph
    input_meta = sess.get_inputs()[0]
    input_name = input_meta.name
    input_shape = input_meta.shape
    
    # Handle dynamic batch dimensions (replace strings/None with 1)
    input_shape = [1 if isinstance(dim, str) or dim is None else dim for dim in input_shape]
    
    # Determine correct numpy datatype based on graph expectations
    dtype = np.float32 if 'float' in input_meta.type else np.int8
    
    # Create dummy data
    if dtype == np.float32:
        dummy_input = {input_name: np.random.randn(*input_shape).astype(dtype)}
    else:
        dummy_input = {input_name: np.random.randint(-128, 127, size=input_shape, dtype=dtype)}

    # 2. Warm-up
    t1 = time.perf_counter()
    for _ in range(WARMUP_RUNS):
        sess.run(None, dummy_input)
    warmup_time_ms = (time.perf_counter() - t1) * 1000.0

    # 3. Main Profiling Loop
    latencies = []
    for _ in range(INFERENCE_RUNS):
        t_start = time.perf_counter()
        sess.run(None, dummy_input)
        t_end = time.perf_counter()
        latencies.append((t_end - t_start) * 1000.0)

    mean_lat = np.mean(latencies)
    p95_lat = np.percentile(latencies, 95)

    print(f"[{model_name} | {precision}] Init: {init_time_ms:.2f}ms | Mean: {mean_lat:.3f}ms | P95: {p95_lat:.3f}ms")

    results.append({
        "model_name": model_name,
        "precision": precision,
        "session_init_ms": round(init_time_ms, 2),
        "warmup_ms": round(warmup_time_ms, 2),
        "mean_latency_ms": round(mean_lat, 3),
        "p95_latency_ms": round(p95_lat, 3)
    })

print("="*75)
print("Starting CPU Pipeline Validation (Mac OS - NOT FOR FINAL REPORT)")
print("="*75)

for model in MODELS:
    fp32_path = f"models/{model}/model.onnx"
    int8_path = f"quantized/qonnx/{model}_int8.onnx"

    if not os.path.exists(int8_path):
        alt_path = f"quantized/qonnx/{model}_qonnx.onnx"
        if os.path.exists(alt_path): int8_path = alt_path
        
    profile_model(fp32_path, model, "FP32")
    profile_model(int8_path, model, "INT8")

# Save exactly to the schema needed for the edge board
df = pd.DataFrame(results)
df.to_csv(CSV_PATH, index=False)

print("-" * 75)
print(f"Validation complete. Schema saved to {CSV_PATH}")
print("Ready for pure data replacement on the target edge board.")